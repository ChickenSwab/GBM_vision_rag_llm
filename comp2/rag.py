CURRENT_DIR = os.path.dirname(os.path.abspath(__file__))

MODEL_NAME = "BAAI/bge-large-en-v1.5"

encoder = None


def load_encoder():

    global encoder

    if encoder is None:

        print("Loading BGE encoder...")

        encoder = SentenceTransformer(
            MODEL_NAME,
            device="cuda"
        )

        print("BGE encoder loaded successfully.")

    return encoder



print("Loading FAISS index...")

